export const settingsCopy = { en, zh }

export function fallbackSettingsCopy(language: string): TranslateSettings {
  const copy = /^zh(?:-|$)/i.test(language) ? zh : en
  return (key, values) => copy[key].replace(/\{(\w+)\}/g, (match, name: string) =>
    values && Object.hasOwn(values, name) ? String(values[name]) : match)
}

export function settingsError(t: TranslateSettings, detail: string, fallback: Key): string {
  if (detail === 'artwork-not-found') return t('artworkMissing')
  if (detail === 'duplicate-id') return t('error.duplicatePackage')
  if (detail === 'package-version-not-newer') return t('error.packageVersion')
  const messages = [
    'error.conflict', 'error.zipType', 'error.zipSize', 'error.uploadMismatch',
    'error.cancelUncertain', 'error.cancelled', 'error.cancelRefresh', 'error.wallpaper',
    'error.otherSkin', 'error.savedUnavailable', 'error.dataMismatch', 'error.background',
    'error.generic', 'validatedRequired',
  ] as const
  return t(messages.find(key => en[key] === detail) ?? fallback)
}
